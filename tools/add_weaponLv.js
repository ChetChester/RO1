const dataPath = path.join(__dirname, '..', 'js', 'data.js');
let data = fs.readFileSync(dataPath, 'utf8');

let updateCount = 0;

for (const [imgIdStr, weaponLv] of Object.entries(weaponLevels)) {
  const imgId = parseInt(imgIdStr);
  
  // 找到對應的物品
  const regex = new RegExp(`"imgId":${imgId}`);
  if (!data.match(regex)) continue;
  
  // 加入 weaponLv
  const addRegex = new RegExp(`("imgId":${imgId}[^}]*?)(})`);
  if (data.match(addRegex)) {
    data = data.replace(addRegex, `$1,"weaponLv":${weaponLv}}`);
    updateCount++;
  }
}

fs.writeFileSync(dataPath, data, 'utf8');
